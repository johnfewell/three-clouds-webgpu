export function turboRgb(t: number): [number, number, number] {
  // Total function: Math.round(NaN) is NaN, so an unguarded lookup indexed the
  // table with NaN and crashed the whole runner on a NaN debug view
  // Callers that care about NaN check it themselves, as computeDiffImage does
  const idx = Number.isFinite(t)
    ? Math.max(0, Math.min(255, Math.round(t * 255)))
    : 0
  return TURBO_SRGB[idx]!
}
